#include <stdio.h>
//AI改了一下注释，更清晰一些
// 第二章节：指针数组
int main() {
    int a = 70, b = 80, c = 90;

    // 指针数组：本质是一个数组，每个元素存的是地址
    int *p[3] = {&a, &b, &c};

    // 用指针移动的方式遍历
    // 我本以为*(p + i)能直接拿到数值，结果打印出来是一串地址
    // 原因：p是数组名，退化成指向数组首元素的指针，首元素是&a（类型 int*）
    // 所以 *(p + i)取出的是第 i 个元素的值，这个值本身就是地址（&a、&b、&c）
    for (int i = 0; i < 3; i++) {
        printf("%d ", *(p + i));   // 改成 %p 打印地址，更准确，当前是为了教学方便
    }
    printf("\n");

    //用数组下标，一下子就对了
    // p[i] 和 *(p+i) 在地址上是等价的，但 p[i] 更符合“数组元素”的直觉
    // p[0] 就是 &a，所以 *p[0] 解引用后得到 a 的值 10
    for (int i = 0; i < 3; i++) {
        printf("%d ", *p[i]);
    }
    printf("\n");

    // 到这里我有点懵：为什么用下标可以，用指针移动就不行？
    // 后来我想通了：下标 p[i] 直接取的是“元素内容”，而指针移动 *(p+i) 也是取“元素内容”
    // 两者本质一样，所以其实 *(p+i) 和 p[i] 拿到的都是地址，只不过我误以为 *(p+i) 是数值了
    // 我前面用 %d 打印 *(p+i) 看到的是地址的十进制表示，当然不是我们想要的数据

    // 那如果我就是想用指针移动来拿到数值，该怎么做？
    // 答案是：再解引用一次！因为 *(p+i) 拿到的是地址，再 * 一下才能取到真正的整数
    for (int i = 0; i < 3; i++) {
        printf("%d ", **(p + i));   // 两层解引用
    }
    printf("\n");

    // --- 对比一下普通整数数组，加深理解 ---
    int arr[3] = {70, 80, 90};
    int *arr_p = arr;   // arr 退化为 &arr[0]，类型 int*

    // 普通数组里存的是整数本身，所以 *(arr_p + i) 一次解引用就得到数值
    for (int i = 0; i < 3; i++) {
        printf("%d ", *(arr_p + i));
    }
    // 我之前试过用 *arr_p[i] 来遍历，直接报错
    // 因为 arr_p[i] 已经是整数了（比如 40），再对它解引用就没意义了
    // 这反过来印证：指针数组的元素本身就是地址，所以需要两层解引用

    printf("\n\n");
    //数组指针:本质是指针
    //场景:二维数组，其他基本用不上
    int q[2][3] = {{10,20,30},{40,50,60}};
    int (*arr_q)[3] = q;   // 指向 q[0]（第一行），类型是 int(*)[3]

    // 看看遍历吧，二维数组遍历
    for(int i=0; i<2; i++) {
        for(int j=0; j<3; j++) {
            printf("%d ", arr_q[i][j]);   // 可以直接用下标，因为 arr_q[i] 等价于 *(arr_q+i)
        }
        printf("\n");
    }
    printf("\n");

    // 那指针该怎么操作呢？一步步解析：
    // 既然本质是指针，那就得用地址去理解它

    printf("%d\n", arr_q);        // 指针变量自身的值：第一行的起始地址（&q[0]）
    printf("%d\n", (*arr_q));     // 解引用后取出第一行，退化为 &q[0][0]（数值相同，但类型变成 int*）
    printf("%d\n", **arr_q);             // 两次解引用，拿到 q[0][0] 的值 10

    // 为什么第一次解引用的结果还是地址？
    // 因为 arr_q 指向的是“一整行”（int[3]），解引用后取出这一行，
    // 而这一行作为数组，在表达式中会退化成首元素的地址（&q[0][0]）
    // 所以它还是地址，只是类型从 int(*)[3] 变成了 int*

    // 用 sizeof 验证类型大小，真相大白：
    printf("arr_q=%zu 字节,  *(arr_q)=%zu 字节,  **(arr_q)=%zu 字节\n", 
        sizeof(arr_q), sizeof(*arr_q), sizeof(**arr_q));
    // arr_q 是 int(*)[3] 类型，指针变量本身占 8 字节（64位系统）
    // *arr_q 是 int[3] 类型，占 12 字节（一整行）
    // **arr_q 是 int 类型，占 4 字节

    // 所以怎么表示第二行第二列元素（q[1][1] 即 50）呢？
    // 用指针运算：先跳行，再跳列，最后解引用
    printf("*(*(arr_q+1)+1) = %d\n", *(*(arr_q+1)+1));   // 输出 50

    // 解析：
    // arr_q + 1：指针移动，arr_q 是指向“3个int的行”的指针，所以 +1 跳 12 字节，指向第二行（q[1]）
    // *(arr_q + 1)：解引用，取出第二行这个数组，退化为 &q[1][0]（int* 类型）
    // *(arr_q + 1) + 1：int* 移动 1 步（4 字节），指向 q[1][1]
    // *(*(arr_q + 1) + 1)：再解引用，拿到 q[1][1] 的值 50
    return 0;
}